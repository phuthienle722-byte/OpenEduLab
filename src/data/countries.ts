/** Toàn bộ danh sách: Việt Nam + Đông Nam Á trước, sau đó là các nước còn lại. */
export const ALL_COUNTRIES: CountryOption[] = [...SOUTHEAST_ASIA_COUNTRIES, ...WORLD_COUNTRIES];

/** Tìm tên hiển thị (tiếng Anh) theo mã quốc gia; trả về mã nếu không tìm thấy. */
export function countryDisplayName(code: string, fallbackNames?: Record<string, string>): string {
  if (!code) return 'VN';
  const found = ALL_COUNTRIES.find((c) => c.code === code);
  if (found) return found.nameEn;
  if (fallbackNames && fallbackNames[code]) return fallbackNames[code];
  return code;
}